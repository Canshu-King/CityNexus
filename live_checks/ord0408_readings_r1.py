"""Materialise ORD-0408's readings into one durable, line-addressable text file.

Every number in the delivery block has to hang off a coordinate a reader can pull up, so the readings are
printed from the artifacts themselves rather than retyped: this script parses the selftest receipt and the two
door receipts and emits `label = value` lines.  The block cites `readings_r1.txt:<line>`, so if a number here
is wrong, the citation points straight at the wrong line instead of at a sentence.
"""
