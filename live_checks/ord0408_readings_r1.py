def load(p):
    return json.load(io.open(p, encoding="utf-8"))


def arm(rep, needle):
    for a in rep["arms"]:
        if needle in a["arm"]:
            return a["reading"]
    return "ARM_NOT_FOUND"


def num(reading, key):
    """Pull one labelled integer out of an arm reading without guessing: the arm prints `key=<int>`."""
    i = reading.index(key + "=") + len(key) + 1
    out = ""
    while i < len(reading) and (reading[i].isdigit() or reading[i] == "-"):
        out += reading[i]
        i += 1
    if not out:
        raise SystemExit("NO_INTEGER_AFTER %s in %r" % (key, reading[:120]))
    return int(out)


def pyval_after(reading, key):
    """Read the Python literal that follows `key=` in an arm reading (dicts and lists included), then evaluate
    it.  Parsing the instrument's own output beats retyping a number into this file."""
    import ast
    i = reading.index(key + "=") + len(key) + 1
    open_ch = reading[i]
    close_ch = {"{": "}", "[": "]"}[open_ch]
    depth = 0
    for j in range(i, len(reading)):
        if reading[j] == open_ch:
            depth += 1
        elif reading[j] == close_ch:
            depth -= 1
            if depth == 0:
                return ast.literal_eval(reading[i:j + 1])
    raise SystemExit("UNTERMINATED_LITERAL after %s in %r" % (key, reading[:160]))


