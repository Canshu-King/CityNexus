def test_the_second_add_of_one_place_names_the_row_that_already_won():
    owner = _traveller("twice")
    shelf = _shelf("重复一次", owner)
    place_id = _place("twice")
    first = client.post(
        f"/api/v1/collections/{shelf['id']}/items",
        json={"place_id": place_id, "note": "第一次"},
        headers=_auth(owner),
    )
    assert first.status_code == 201, first.text
    second = client.post(
        f"/api/v1/collections/{shelf['id']}/items",
        json={"place_id": place_id, "note": "第二次"},
        headers=_auth(owner),
    )
    assert second.status_code == 409, second.text
    assert _reason(second.json()) == "PLACE_ALREADY_IN_COLLECTION", second.text
    details = _details(second.json())
    assert details["existing_item_id"] == first.json()["id"], details
    assert details["existing_added_at"] == first.json()["added_at"], details
    # And the shelf still holds exactly one row -- the loser wrote nothing.
    stored = _find_shelf(shelf["id"], owner)
    assert stored["item_count"] == 1, stored
    assert [row["note"] for row in stored["items"]] == ["第一次"], stored


def test_absence_is_a_list_and_the_list_door_has_no_way_to_404():
    """「还没有收藏」 has to be expressible, so the door cannot answer it with a 404.

    Changed from the source, and this is the pair the retrofit bought: there the door's only
    requirement was a `traveler_id` and omitting it was a 422, because nothing else could scope the
    read.  Here a traveller who owns nothing is still answered 200 and `[]`, and the two ways to
    fail are 401 (no credential) and a named 422 (a credential *plus* the parameter that used to
    open the door).  Neither failure can return anybody's rows.
    """

    owner = _traveller("nobody-here")
    body = _shelves(owner)
    assert body == [], "a traveller that never created a shelf must read no rows"
    unscoped = client.get("/api/v1/collections")
    assert unscoped.status_code != 404, unscoped.text
    _assert_unauthorized(unscoped)
    listed_params = (_contract()["paths"]["/collections"]["get"].get("parameters") or [])
    assert listed_params == [], "the contract must not re-announce a traveler_id parameter"


