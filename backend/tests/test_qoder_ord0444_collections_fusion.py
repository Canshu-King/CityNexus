def test_the_owner_can_take_a_shelf_away_and_its_rows_go_with_it():
    """The shelf-level DELETE the imported tree never grew, and the CASCADE that was kept.

    The rows leave through `collection_items.folder_id ... ON DELETE CASCADE` rather than a second
    statement -- the counterpart of `owner_traveler_id`'s deliberate NO ACTION, and both readings
    are pinned in arm 1.
    """

    a = _traveller("delete-a")
    b = _traveller("delete-b")
    shelf = _shelf("待删除", a)
    place_id = _place("delete")
    assert client.post(
        f"/api/v1/collections/{shelf['id']}/items",
        json={"place_id": place_id},
        headers=_auth(a),
    ).status_code == 201

    # A stranger cannot delete it, and gets the absent-shelf answer so this door is not a probe.
    refused = client.delete(f"/api/v1/collections/{shelf['id']}", headers=_auth(b))
    assert refused.status_code == 404, refused.text
    assert _reason(refused.json()) == "COLLECTION_FOLDER_NOT_FOUND", refused.text
    assert _find_shelf(shelf["id"], a) is not None, "the refused delete changed nothing"

    anonymous = client.delete(f"/api/v1/collections/{shelf['id']}")
    assert anonymous.status_code == 401, anonymous.text

    gone = client.delete(f"/api/v1/collections/{shelf['id']}", headers=_auth(a))
    assert gone.status_code == 204, gone.text
    assert gone.content == b"", "204 carries no body"

    with sqlite3.connect(_store_path()) as connection:
        folders = connection.execute(
            "SELECT count(*) FROM collection_folders WHERE id = ?", (shelf["id"],)
        ).fetchone()[0]
        items = connection.execute(
            "SELECT count(*) FROM collection_items WHERE folder_id = ?", (shelf["id"],)
        ).fetchone()[0]
    assert folders == 0, folders
    assert items == 0, "the cascade is the thing this arm exists to measure"
    assert _find_shelf(shelf["id"], a) is None
    # And the door stays a 404 afterwards rather than turning the absence into a 500.
    again = client.delete(f"/api/v1/collections/{shelf['id']}", headers=_auth(a))
    assert again.status_code == 404, again.text
    assert _reason(again.json()) == "COLLECTION_FOLDER_NOT_FOUND", again.text
