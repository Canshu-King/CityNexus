def test_a_shelf_is_answered_to_its_owner_and_to_nobody_else():
    """The source could only prove scoping-by-column; the door now proves it per traveller.

    Two travellers, two credentials, one shelf.  A's read contains it, B's read does not, and B has
    no way to ask for it -- there is nothing on this door left to ask with.
    """

    a = _traveller("authz-a")
    b = _traveller("authz-b")
