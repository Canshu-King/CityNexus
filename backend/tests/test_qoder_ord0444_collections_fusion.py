    theirs = _shelf("只属于乙", b)

    ids_a = [item["id"] for item in _shelves(a)]
    assert mine["id"] in ids_a, ids_a
    assert theirs["id"] not in ids_a, ids_a

    ids_b = [item["id"] for item in _shelves(b)]
    assert theirs["id"] in ids_b, ids_b
    assert mine["id"] not in ids_b, ids_b

