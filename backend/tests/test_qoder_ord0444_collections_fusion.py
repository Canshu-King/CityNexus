def test_the_contract_declares_the_doors_and_no_control_they_lack():
    """The hand contract travels with the door, including the inputs the door no longer has."""

    paths = _contract()["paths"]
    listed = paths["/collections"]["get"]
    created = paths["/collections"]["post"]
    added = paths["/collections/{folder_id}/items"]["post"]
    assert listed["operationId"] == "listCollections", listed
    assert created["operationId"] == "createCollection", created
    assert added["operationId"] == "addCollectionItem", added
    # AUTH RETROFIT, contract side: the source declared a required `traveler_id` query parameter
    # here and said the id was "matched, not authenticated".  There is no parameter left to declare.
    assert listed.get("parameters") is None, listed.get("parameters")
    # ...and the create body takes only a name.
    create_shape = _contract()["components"]["schemas"]["CollectionFolderCreate"]
    assert create_shape["required"] == ["name"], create_shape
    assert create_shape["additionalProperties"] is False, create_shape
    assert "owner_traveler_id" not in create_shape["properties"], create_shape
    # Nothing that is not a control may ride in on the list door: no pagination, no sort.
    # Same ruler as the source test (@470), applied to the door's *inputs* -- its prose is allowed to
    # say the word "sort" while declaring that it does not take one.
    listed_params = listed.get("parameters") or []
    for forbidden in ("page", "limit", "offset", "sort", "order"):
        assert forbidden not in json.dumps(listed_params), forbidden
        assert forbidden not in json.dumps(listed.get("requestBody") or {}), forbidden
    # The owner is still an OUTPUT of the read -- the screen has to be able to say whose shelf it is.
    assert "owner_traveler_id" in _contract()["components"]["schemas"]["CollectionFolder"]["properties"]
    added_item = paths["/collections/{folder_id}/items"]
    assert [p["$ref"].rsplit("/", 1)[-1] for p in added_item["parameters"]] == ["CollectionFolderId"], added_item["parameters"]
    folder_id = _contract()["components"]["parameters"]["CollectionFolderId"]
