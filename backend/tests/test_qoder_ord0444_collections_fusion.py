def _auth(traveller_id: str | None) -> dict[str, str]:
    """The credential for a traveller, or no credential at all for `None`.

    Minted by the product's own server-side signer (`issue_traveler_token`), which is documented as
    the helper a trusted process uses; there is no endpoint on this server that hands out tokens for
    an id someone names, and that asymmetry is the point of the whole retrofit.
    """

    if traveller_id is None:
        return {}
    return {"Authorization": f"Bearer {issue_traveler_token(traveller_id)}"}


def _shelf(name: str, owner: str) -> dict:
    created = client.post("/api/v1/collections", json={"name": name}, headers=_auth(owner))
    assert created.status_code == 201, created.text
    body = created.json()
    # The answer carries the归属 the credential established, which is the caller -- and there is no
    # input on this door through which it could have been anybody else.
    assert body["owner_traveler_id"] == owner, body
    return body


def _shelves(owner: str | None) -> list[dict]:
    answer = client.get("/api/v1/collections", headers=_auth(owner))
    assert answer.status_code == 200, answer.text
    body = answer.json()
    assert isinstance(body, list), type(body)
    return body


def _find_shelf(shelf_id: str, owner: str) -> dict | None:
    return next((item for item in _shelves(owner) if item["id"] == shelf_id), None)


def _reason(body: object) -> str | None:
    error = (body or {}).get("error") if isinstance(body, dict) else None
    if isinstance(error, dict):
        code = error.get("reason_code")
        if isinstance(code, str) and code:
            return code
    if isinstance(body, dict):
        code = body.get("reason_code")
        if isinstance(code, str) and code:
            return code
    return None


def _code(body: object) -> str | None:
    error = (body or {}).get("error") if isinstance(body, dict) else None
    return error.get("code") if isinstance(error, dict) else None


def _message_key(body: object) -> str | None:
    error = (body or {}).get("error") if isinstance(body, dict) else None
    return error.get("message_key") if isinstance(error, dict) else None


def _details(body: object) -> dict:
    error = (body or {}).get("error") if isinstance(body, dict) else None
    if isinstance(error, dict) and isinstance(error.get("details"), dict):
        return error["details"]
    if isinstance(body, dict) and isinstance(body.get("details"), dict):
        return body["details"]
    return {}


def _assert_unauthorized(response) -> None:
    """401, in the envelope this tree already uses for it -- asserted, not assumed.

    `app/main.py`'s HTTPException handler maps a status to a `code` through
    {404: NOT_FOUND, 409: CONFLICT, 422: VALIDATION_ERROR} and falls through to REQUEST_ERROR for
    everything else, and `HTTP_MESSAGE_KEYS` carries no 401 entry either.  So a bare
    `HTTPException(401, ...)` from `resolve_traveler_principal` -- the shape every authenticated
    fusion door already raises, and the one this port reuses rather than inventing -- answers
    `code = REQUEST_ERROR`, `message_key = error.request_error`.

    Two things are pinned here because they are the ones that matter for the stop condition: the
    status is 4xx and the body carries no shelves.  The `code` string is asserted as it actually
    renders, not as a nicer name this branch does not have; renaming 401's envelope would be a
    change to a baseline handler that roughly thirty other modules depend on, and it is out of this
    slice's way.
    """

    assert response.status_code == 401, response.text
    body = response.json()
    assert _code(body) == "REQUEST_ERROR", response.text
    assert _message_key(body) == "error.request_error", response.text
    # The refusal path leaks no shelf payload, under any spelling.
    dumped = json.dumps(body, ensure_ascii=False)
    assert "item_count" not in dumped, response.text
    assert "owner_traveler_id" not in dumped, response.text


