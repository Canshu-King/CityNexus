# --- arm 1: the container is in the store, and the two fusion-import decisions are readable ----


def test_the_two_tables_and_the_durability_index_are_in_the_store():
    """`sqlite_master` says the container exists; an ORM class alone would not have proved it.

    Read out of the store this process writes, which is also the proof that the tables came from
    `backend/db/schema.sql`: this tree builds no tables from `Base.metadata`, and the model classes
    in `app/db/models.py` declare rows rather than creating them.
    """

    with sqlite3.connect(_store_path()) as connection:
        names = {
            row[0]
            for row in connection.execute(
                "SELECT name FROM sqlite_master WHERE type='table' AND name IN "
                "('collection_folders','collection_items')"
            )
        }
        assert names == {"collection_folders", "collection_items"}, names
        folder_columns = {row[1] for row in connection.execute("PRAGMA table_info(collection_folders)")}
        item_columns = {row[1] for row in connection.execute("PRAGMA table_info(collection_items)")}
        assert folder_columns == {
            "id",
            "name",
            "owner_traveler_id",
            "created_at",
            "updated_at",
        }, sorted(folder_columns)
        assert item_columns == {"id", "folder_id", "place_id", "note", "added_at"}, sorted(item_columns)
        # 成员归属 is not a caption someone hoped would be filled in: `notnull` = 1 is the column
        # flag the store enforces, and the reference itself is only readable from `foreign_key_list`.
        owner_column = next(
            r for r in connection.execute("PRAGMA table_info(collection_folders)")
            if r[1] == "owner_traveler_id"
        )
        assert owner_column[3] == 1, owner_column
        owner_fks = [
            r for r in connection.execute("PRAGMA foreign_key_list(collection_folders)")
            if r[3] == "owner_traveler_id"
        ]
        assert len(owner_fks) == 1, owner_fks
        # (id, seq, table, from, to, on_update, on_delete, match)
        assert owner_fks[0][2] == "travelers" and owner_fks[0][4] == "id", owner_fks
        # FUSION IMPORT DECISION (1/2), and the source's own verdict kept: NO ACTION, not CASCADE.
        # Deleting a traveller must not silently take their shelves, even though the neighbouring
        # fusion tables at schema.sql:716/:784 do use `ON DELETE CASCADE` on the same column name.
        assert owner_fks[0][6] == "NO ACTION", owner_fks
        # FUSION IMPORT DECISION (2/2), the opposite choice on the other leg and deliberately so:
        # a shelf row whose shelf is gone has no owner and no reader, so it does cascade.
        item_fks = {
            r[3]: r for r in connection.execute("PRAGMA foreign_key_list(collection_items)")
        }
        assert item_fks["folder_id"][2] == "collection_folders", item_fks
        assert item_fks["folder_id"][6] == "CASCADE", item_fks
        assert item_fks["place_id"][2] == "places", item_fks
        assert item_fks["place_id"][6] == "NO ACTION", item_fks

        index_list = list(connection.execute("PRAGMA index_list(collection_items)"))
        columns_of = {
            row[1]: [r[2] for r in connection.execute(f"PRAGMA index_info('{row[1]}')")]
            for row in index_list
        }
        # SQLite implements a table-level UNIQUE as an *autoindex* whose `sql` column in
        # `sqlite_master` is NULL, so reading `sql` for the word "UNIQUE" would have said "no
        # constraint" about a constraint that is there.  `PRAGMA index_list` reports it honestly:
        # `origin` = 'u' is a UNIQUE constraint, and `unique` = 1 is the flag the planner enforces.
        unique_constraints = [
            (name, columns_of[name])
            for (_seq, name, _u, origin, _partial) in index_list
            if origin == "u"
        ]
        assert len(unique_constraints) == 1, unique_constraints
        constraint_name, constraint_columns = unique_constraints[0]
        assert constraint_name.startswith("sqlite_autoindex_collection_items_"), constraint_name
        assert constraint_columns == ["folder_id", "place_id"], unique_constraints
        assert "idx_collection_items_folder_added" in columns_of, sorted(columns_of)
        assert columns_of["idx_collection_items_folder_added"] == ["folder_id", "added_at"], columns_of
        folder_indexes = list(connection.execute("PRAGMA index_list(collection_folders)"))
        folder_columns_of = {
            row[1]: [r[2] for r in connection.execute(f"PRAGMA index_info('{row[1]}')")]
            for row in folder_indexes
        }
        assert "idx_collection_folders_owner" in folder_columns_of, sorted(folder_columns_of)
        assert folder_columns_of["idx_collection_folders_owner"] == [
            "owner_traveler_id",
            "created_at",
        ], folder_columns_of


