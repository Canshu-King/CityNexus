import { chromium } from "file:///D:/moodle/_cmdr_rescue_v3_1022/frontend/node_modules/playwright/index.mjs";
import fs from "node:fs";
const BASE = "http://127.0.0.1:14492";
const OUT = "D:/moodle/_cmdr_rescue_v3_1022/trial/results/20261022_v3_human_chrome";
const lines = [];
const note = (v) => { lines.push(v); fs.writeFileSync(OUT + "/map-traveller-real-1.txt", lines.join("\n") + "\n", "utf8"); };
const browser = await chromium.launch({ headless: true });
const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 1 });
await ctx.addInitScript(() => { localStorage.clear(); sessionStorage.clear(); });
const page = await ctx.newPage();
const errors = [];
page.on("pageerror", (e) => errors.push(String(e).slice(0, 160)));
await page.goto(BASE + "/revolution", { waitUntil: "networkidle", timeout: 45000 }).catch(() => {});
await page.waitForTimeout(1200);
await page.locator('[data-testid="rev-mobile-tab-trips"]').click().catch(() => {});
await page.waitForTimeout(1000);
await page.locator('[data-testid="rev-demo-session"]').click().catch(() => {});
await page.waitForTimeout(3200);
const mapTab = page.getByRole("button", { name: "地图", exact: true }).first();
note("MAP_TAB " + JSON.stringify(await mapTab.count()));
await mapTab.click().catch(() => {});
await page.waitForTimeout(1200);
const load = page.getByRole("button", { name: /加载地图/ }).first();
note("LOAD_BUTTON " + JSON.stringify(await load.count()));
await load.click().catch(() => {});
let visible = false;
for (let i = 0; i < 20; i++) {
  visible = await page.locator('[data-testid="rev-map-traveller"]').isVisible().catch(() => false);
  if (visible) break;
  await page.waitForTimeout(1000);
}
note("MARKER_VISIBLE " + JSON.stringify(visible));
note("MARKER_COUNT " + JSON.stringify(await page.locator('[data-testid="rev-map-traveller"]').count()));
note("STATE_LINE " + JSON.stringify(await page.locator('[data-testid="rev-map-traveller-state"]').innerText().catch(() => "")));
note("CAPTION " + JSON.stringify(await page.locator('[aria-label="当前行程地图"] p').first().innerText().catch(() => "")));
note("ERRORS " + JSON.stringify(errors.slice(0, 6)));
await page.locator('[data-testid="rev-map-traveller-state"]').scrollIntoViewIfNeeded().catch(() => {});
await page.screenshot({ path: OUT + "/map-traveller-real-390.png" });
await browser.close();
