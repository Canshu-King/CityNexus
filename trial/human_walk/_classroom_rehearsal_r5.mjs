note("PROPOSAL_TEXT " + JSON.stringify(await page.locator('[data-testid="rev-guardian-proposal-diff"]').innerText().catch(() => "")));
const box = await card.boundingBox().catch(() => null);
note("PROPOSAL_BOX " + JSON.stringify(box));
if (box) note("PROPOSAL_IN_VIEW " + JSON.stringify(box.y >= 0 && box.y + box.height <= 932 && box.height > 40));
await page.screenshot({ path: OUT + "/rehearsal5-guardian.png" });
await page.locator('[data-testid="rev-guardian-accept-replan"]').click(); mark("accept");
await page.waitForTimeout(5500);
let body = "";
for (let i = 0; i < 5; i++) { body = await page.evaluate(() => document.body.innerText); if (/第一站：/.test(body)) break; await page.waitForTimeout(1200); }
note("AFTER_FIRST_STOP " + JSON.stringify((body.split("第一站：")[1] || "").split(NL)[0]));
mark("after-reload");
const strip = page.locator('[data-testid="rev-classroom-clock"]');
await strip.scrollIntoViewIfNeeded().catch(() => {});
note("CLOCK_BEFORE " + JSON.stringify(await page.locator('[data-testid="rev-clock-virtual"]').innerText().catch(() => "")));
await page.locator('[data-testid="rev-clock-plus60"]').click().catch(() => {});
await page.waitForTimeout(1500);
note("CLOCK_AFTER " + JSON.stringify(await page.locator('[data-testid="rev-clock-virtual"]').innerText().catch(() => "")));
mark("clock");
await page.getByRole("button", { name: "地图", exact: true }).first().click().catch(() => {});
await page.waitForTimeout(800);
await page.getByRole("button", { name: /加载地图/ }).first().click().catch(() => {});
let dot = false;
for (let i = 0; i < 15; i++) { dot = await page.locator('[data-testid="rev-map-traveller"]').isVisible().catch(() => false); if (dot) break; await page.waitForTimeout(1000); }
note("BLUE_DOT " + JSON.stringify(dot));
note("DOT_STATE " + JSON.stringify(await page.locator('[data-testid="rev-map-traveller-state"]').innerText().catch(() => "")));
mark("map");
note("TOTAL_S " + ((Date.now() - started) / 1000).toFixed(1));
note("ERRORS " + JSON.stringify(errors.slice(0, 6)));
await page.screenshot({ path: OUT + "/rehearsal5-final.png" });
await browser.close();
