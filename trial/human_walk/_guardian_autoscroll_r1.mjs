import { chromium } from "file:///D:/moodle/_cmdr_rescue_v3_1022/frontend/node_modules/playwright/index.mjs";
import fs from "node:fs";
const BASE = "http://127.0.0.1:14492";
const OUT = "D:/moodle/_cmdr_rescue_v3_1022/trial/results/20261022_v3_human_chrome";
const lines = [];
const note = (v) => { lines.push(v); fs.writeFileSync(OUT + "/guardian-autoscroll-1.txt", lines.join("\n") + "\n", "utf8"); };
const browser = await chromium.launch({ headless: true });
const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 1 });
await ctx.addInitScript(() => { localStorage.clear(); sessionStorage.clear(); });
const page = await ctx.newPage();
const errors = [];
page.on("pageerror", (e) => errors.push(String(e).slice(0, 160)));
await page.goto(BASE + "/revolution", { waitUntil: "networkidle", timeout: 45000 }).catch(() => {});
await page.waitForTimeout(1200);
await page.locator('[data-testid="rev-mobile-tab-trips"]').click().catch(() => {});
await page.waitForTimeout(1000);
await page.locator('[data-testid="rev-demo-session"]').click().catch(() => {});
await page.waitForTimeout(3200);
await page.getByRole("button", { name: /行程守护/ }).first().click().catch(() => {});
await page.waitForTimeout(2500);
const card = page.locator('[data-testid="rev-guardian-proposal"]');
const box = await card.boundingBox();
note("BOX " + JSON.stringify(box));
note("IN_VIEWPORT " + JSON.stringify(Boolean(box && box.y >= 0 && box.y + box.height <= 844)));
note("SCROLL_Y " + JSON.stringify(await page.evaluate(() => Math.round(window.scrollY))));
note("TEXT " + JSON.stringify(await page.locator('[data-testid="rev-guardian-proposal-diff"]').innerText().catch(() => "")));
note("ERRORS " + JSON.stringify(errors));
await page.screenshot({ path: OUT + "/guardian-autoscroll-390.png" });
await browser.close();
