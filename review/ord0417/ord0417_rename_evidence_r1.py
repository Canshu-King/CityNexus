"""ORD-0417 lane: re-deliver two colliding evidence instruments under new names.

The commander's read-only re-cut of `review/R-ord0417-tap-names-stop-r2` reported add/add collisions
on exactly two paths, both of which are also on the authoritative line:
`review/ord0417/ord0417_commit_r1.py` and `review/ord0417/ord0417_pack_evidence_r1.py`.  The standing
rule is that a re-delivery must go out under new names and must not touch a published path, so this
instrument does that and nothing else.

Two things it deliberately does NOT do:
  * it does not re-hash or edit the two files.  It grafts r2's own blob ids, so what lands is byte-for-
    byte the version r2 carried -- editing them to add a warning header would quietly turn an evidence
    copy into a new artifact.
  * it does not pretend the two copies are current.  Both are measured here against the line's versions
    and the answer goes into the provenance note that ships beside them: r2's copies are the OLDER
    generation (the line's `ord0417_commit_r1.py` gained an `ORD0417_EXP` env override that r2's copy
    does not have), so a reader who runs the renamed copy gets the pre-fix behaviour.  That is a fact for
    the commander to weigh, not for me to fix by rewriting history.

usage: python ord0417_rename_evidence_r1.py --tip <40-hex> --branch <ref> [--apply]
"""
import argparse
import json
import os
import subprocess
import sys
import tempfile

REPO = r"D:/moodle/CityNexus"
R2 = "6020871f0452cc4b1844dd8cc78b4acbeb294595"
RENAMES = [
    ("review/ord0417/ord0417_commit_r1.py", "review/ord0417/ord0417_commit_r2.py"),
    ("review/ord0417/ord0417_pack_evidence_r1.py", "review/ord0417/ord0417_pack_evidence_r2.py"),
]


def git(*args):
    r = subprocess.run(["git", "-C", REPO, *args], capture_output=True, text=True)
    if r.returncode != 0:
        raise SystemExit(f"git {' '.join(args)} -> rc={r.returncode} {r.stderr.strip()[:200]}")
    return (r.stdout or "").strip()


def size_of(blob):
    return int(git("cat-file", "-s", blob))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--tip", required=True)
    ap.add_argument("--branch", required=True)
    ap.add_argument("--apply", action="store_true")
    args = ap.parse_args()

    adds = []
    for old, new in RENAMES:
        blob = git("rev-parse", f"{R2}:{old}")
        if git("cat-file", "-t", blob) != "blob":
            raise SystemExit(f"REFUSE: r2's {old} is not a blob")
        if subprocess.run(["git", "-C", REPO, "cat-file", "-e", f"{args.tip}:{new}"],
                          capture_output=True).returncode == 0:
            raise SystemExit(f"REFUSE: new name {new} is already on the line")
        line_blob = git("rev-parse", f"{args.tip}:{old}")
        adds.append({
            "old_path_on_line": old, "old_blob_on_line": line_blob,
            "r2_blob_carried": blob, "new_path": new, "bytes": size_of(blob),
            "identical_to_line": blob == line_blob,
            "diff_vs_line": git("diff", "--numstat", f"{args.tip}:{old}", f"{R2}:{old}"),
        })

    note_lines = ["# ORD-0417 evidence rename, generated by ord0417_rename_evidence_r1.py",
                  f"r2 commit: {R2}", f"grafted onto: {args.tip}", ""]
    for a in adds:
        note_lines += [
            f"{a['old_path_on_line']}  ->  {a['new_path']}",
            f"  carried blob (r2's bytes): {a['r2_blob_carried']}  ({a['bytes']} B)",
            f"  blob still on the line under the old name: {a['old_blob_on_line']}",
            f"  identical: {a['identical_to_line']}   numstat line-vs-r2: {a['diff_vs_line'] or '(none)'}",
            "  meaning: r2's copy is an EARLIER generation of the same instrument, not new evidence.",
            "",
        ]
    note = chr(10).join(note_lines)
    note_path = "review/ord0417/RENAME_MAP_R2_R1.txt"

    idx = tempfile.NamedTemporaryFile(prefix="ord0417rn_", suffix=".idx", delete=False)
    idx.close()
    env = dict(os.environ, GIT_INDEX_FILE=idx.name)
    try:
        subprocess.run(["git", "-C", REPO, "read-tree", args.tip], env=env, check=True, capture_output=True)
        note_blob = subprocess.run(["git", "-C", REPO, "hash-object", "-w", "--no-filters", "--stdin"],
                                   input=note.encode("utf-8"), capture_output=True, check=True).stdout.decode().strip()
        # the instrument that made this commit ships beside it, hashed from disk with --no-filters
        self_blob = git("hash-object", "-w", "--no-filters",
                        f"{REPO}/../_qoder_b_ord0417_20260928/run/ord0417_rename_evidence_r1.py")
        for spec in [a["new_path"] for a in adds] + [note_path, "review/ord0417/ord0417_rename_evidence_r1.py"]:
            blob = next((x["r2_blob_carried"] for x in adds if x["new_path"] == spec),
                        self_blob if spec.endswith("rename_evidence_r1.py") else note_blob)
            subprocess.run(["git", "-C", REPO, "update-index", "--add", "--cacheinfo",
                            f"100644,{blob},{spec}"], env=env, check=True, capture_output=True)
        tree = subprocess.run(["git", "-C", REPO, "write-tree"], env=env, check=True,
                              capture_output=True, text=True).stdout.strip()
        msg = ("ORD-0417 evidence: r2's two colliding instruments re-delivered under new names\n"
               "\n"
               f"The commander's re-cut of {R2} hit add/add on two evidence paths that are also on\n"
               "the line, so the standing rule applies: a re-delivery takes a new name and never a published path.\n"
               f"This commit grafts onto {args.tip} and adds four paths:\n"
               "  ord0417_commit_r1.py        -> ord0417_commit_r2.py        (r2's bytes, verbatim)\n"
               "  ord0417_pack_evidence_r1.py -> ord0417_pack_evidence_r2.py (r2's bytes, verbatim)\n"
               "  RENAME_MAP_R2_R1.txt        -- the mapping, both blob ids, and the measured fact that\n"
               "       r2's copies are the EARLIER generation (the line's commit instrument gained an\n"
               "       ORD0417_EXP override r2's copy does not have).  Nothing here is presented as new\n"
               "       evidence; it is the same evidence, reachable without an overwrite.\n"
               "  ord0417_rename_evidence_r1.py -- this instrument, so the mapping can be re-derived.\n")
        commit = git("commit-tree", tree, "-p", args.tip, "-m", msg)
        print(json.dumps({"tip": args.tip, "tree": tree, "commit": commit, "adds": adds,
                          "note_blob": note_blob, "applied": bool(args.apply)}, indent=1))
        if args.apply:
            git("update-ref", args.branch, commit)
            print("ref moved:", args.branch)
    finally:
        os.unlink(idx.name)


if __name__ == "__main__":
    main()
