"""ORD-0395 shape probe: what each of the three surfaces currently claims about the reset door.

Every number in the output is read out of the tree or out of the application in this process, so the
delivery block can cite the emitted file instead of a typed figure.
"""

from __future__ import annotations

import re
from pathlib import Path

import yaml
from fastapi.testclient import TestClient

from app.main import DEMO_RESET_REFUSALS, app

WT = Path(r"D:/moodle/_qoder_lane_heyuegong_20261009/wt")
CODE_NAME = re.compile(r"\b[A-Z][A-Z0-9]*(?:_[A-Z0-9]+)+\b")
client = TestClient(app)

served = client.get("/openapi.json").json()["paths"]["/api/v1/demo/reset"]["post"]
contract = yaml.safe_load((WT / "contracts" / "openapi.yaml").read_text(encoding="utf-8"))
door = contract["paths"]["/demo/reset"]["post"]
part = [item for item in door["responses"]["403"]["content"]["application/json"]["schema"]["allOf"] if "properties" in item][0]

rows = [
    "ORD-0395 shape probe -- served /openapi.json vs contracts/openapi.yaml vs the code's refusal table.",
    f"generated by review/ord0395/served_shape_probe_r1.py; run from backend/ with the repo venv",
    "",
    f"served statuses for POST /demo/reset: {sorted(served['responses'])}",
    f"contract statuses for POST /demo/reset: {sorted(door['responses'])}",
    f"served 403 declares a response body: {'content' in served['responses']['403']}",
    f"contract 403 declares a response body: {'content' in door['responses']['403']}",
    f"contract error.code enum: {part['properties']['error']['properties']['code']['enum']}",
    f"code names found in the served 403 description: {sorted(CODE_NAME.findall(served['responses']['403']['description']))}",
    f"codes in app.main.DEMO_RESET_REFUSALS: {sorted(DEMO_RESET_REFUSALS)}",
    f"served parameter claim: {served['parameters']}",
    f"contract parameter claim: {door['parameters']}",
]
text = "\n".join(rows) + "\n"
out = WT / "review" / "ord0395" / "SHAPE_PROBE_R1.txt"
out.write_text(text, encoding="utf-8")
print(text)
print(f"lines_in_output={len(text.splitlines())}")
