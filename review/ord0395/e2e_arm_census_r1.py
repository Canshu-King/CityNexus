"""ORD-0395 census: which acceptance specs reach for the reset door, and with what claim.

Computed from the tree, not typed. A line counts only if it is code (block comments and `*`-prefixed
docstring lines are skipped) and carries the quoted route literal; the request form is then found by
walking back a few lines, so the multi-line `post(\n  "/api/v1/demo/reset",` shape is not lost.
A site is "untokened" when no `X-Demo-Reset-Token` appears anywhere in the statement around it.
"""

from __future__ import annotations

import re
from pathlib import Path

WT = Path(r"D:/moodle/_qoder_lane_heyuegong_20261009/wt")
ROOT = WT / "frontend" / "e2e"
LITERAL = '"/api/v1/demo/reset"'
HEADER = "X-Demo-Reset-Token"
OPENERS = (".post(", "fetch(", "waitForResponse", ".url().includes(")
GENERIC_CALL = re.compile(r"\b(?:call|api)<[^(]*\(")

request_kinds: dict[str, list[str]] = {"post": [], "watch": [], "other": []}
tokened: list[str] = []


def is_code(line: str, in_block: bool) -> tuple[bool, bool]:
    stripped = line.strip()
    if in_block:
        return False, "*/" not in stripped
    if stripped.startswith("/*"):
        return False, "*/" not in stripped
    if not stripped or stripped.startswith(("*", "//")):
        return False, False
    return True, False


def opener_of(lines: list[str], index: int) -> str:
    for back in range(0, 5):
        if index - back < 0:
            break
        row = lines[index - back]
        if "waitForResponse" in row or ".url().includes(" in row:
            return "watch"
        if any(token in row for token in (".post(", "fetch(")) or GENERIC_CALL.search(row):
            return "post"
    return "other"


for path in sorted(ROOT.rglob("*.ts")):
    lines = path.read_text(encoding="utf-8", errors="replace").splitlines()
    flags, in_block = [], False
    for line in lines:
        code, in_block = is_code(line, in_block)
        flags.append(code)
    for index, line in enumerate(lines):
        if not flags[index] or LITERAL not in line:
            continue
        site = f"{path.relative_to(WT).as_posix()}:{index + 1}"
        window = "\n".join(lines[max(0, index - 4): index + 10])
        kind = opener_of(lines, index)
        request_kinds[kind].append(site)
        if HEADER in window:
            tokened.append(site)

untokened = [site for sites in request_kinds.values() for site in sites if site not in tokened]
rows = [
    "ORD-0395 census: acceptance specs that reach for POST /api/v1/demo/reset.",
    "Generated by review/ord0395/e2e_arm_census_r1.py; every site is file:line read off this tree.",
    "",
    f"request sites (a call built in the test itself): {len(request_kinds['post'])}",
    *request_kinds["post"],
    f"watch sites (the spec waits for a response the screen produced): {len(request_kinds['watch'])}",
    *request_kinds["watch"],
    f"other sites (a literal that is not a request): {len(request_kinds['other'])}",
    *request_kinds["other"],
    f"sites that present {HEADER}: {len(tokened)}",
    *tokened,
    f"sites that present no token: {len(untokened)}",
    *untokened,
]
text = "\n".join(rows) + "\n"
out = WT / "review" / "ord0395" / "E2E_ARM_CENSUS_R1.txt"
out.write_text(text, encoding="utf-8")
print(text)
print(f"lines_in_output={len(text.splitlines())}")
